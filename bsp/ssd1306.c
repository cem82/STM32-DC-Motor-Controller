#define FONT_FIRST_CHAR  32    // ASCII code of the first row (' ')
#define FONT_LAST_CHAR   126   // ASCII code of the last row ('~')
#define CHAR_WIDTH       6     // 5 font columns + 1 empty column between letters

static uint8_t s_cur_x    = 0;   // cursor: pixel column 0..127
static uint8_t s_cur_line = 0;   // cursor: text line (page) 0..7

void ssd1306_set_cursor(uint8_t x, uint8_t line)
{
    s_cur_x    = x;
    s_cur_line = line;
}

void ssd1306_clear_line(uint8_t line)
{
    memset(&s_buf[line * SSD1306_WIDTH], 0x00, SSD1306_WIDTH);   // 128 bytes = one text line
}

static void write_char(char ch)
{
    if (ch < FONT_FIRST_CHAR || ch > FONT_LAST_CHAR)
    {
        ch = '?';                                   // unknown character -> '?'
    }
    if (s_cur_x + CHAR_WIDTH > SSD1306_WIDTH)
    {
        return;                                     // no room left on this line
    }

    const uint8_t *glyph = k_font5x7[ch - FONT_FIRST_CHAR];     // row in the font table
    uint16_t idx = s_cur_line * SSD1306_WIDTH + s_cur_x;        // byte in the framebuffer

    for (uint8_t i = 0; i < 5; i++)
    {
        s_buf[idx + i] = glyph[i];                  // copy the 5 columns
    }
    s_buf[idx + 5] = 0x00;                          // empty column after the letter

    s_cur_x += CHAR_WIDTH;                          // move cursor to the next position
}

void ssd1306_write_string(const char *s)
{
    while (*s != '\0')        // a C string ends with the '\0' character
    {
        write_char(*s);
        s++;                  // next character
    }
}
